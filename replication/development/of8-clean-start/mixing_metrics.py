"""Metrics for the bounded 2-D two-stream cold-mixing case.

Reads the written fields of a case generated by `prepare_mixing_case.py` and reports, per
write time:

  * mass, x-momentum and total-energy flux through the inlet and outlet patches, the
    measured accumulation rate, and the resulting imbalance. The inlet flux is *exact*: it
    is fixed by the `fixedValue` inlet profile and by the receipt's densities/velocities.
    The outlet flux is integrated over the outlet patch cells.
  * a mixing-width diagnostic: the transverse extent between the 10 % and 90 % crossings of
    the oxidiser mass fraction, and the 50 % crossing position.
  * bounds and closure: min/max of T, rho, p and Y, the species sum error, the maximum Mach
    number and the number of cells with negative species mass fraction.

The balance identities used here are stated rather than assumed:

  mass      d/dt sum(rho V)        =  F_in - F_out
  momentum  d/dt sum(rho u V)      =  (M_in - M_out) + (p_in A_in - p_out A_out)
                                      with the *convective* flux M = rho u^2 A only
  energy    d/dt sum((rho(hs+hf+K) - p) V) = Fin_e - Fout_e  (+ conduction at the open ends)

Batch r6/r12 subtracted the outlet pressure twice: the integrated outlet flux already carried
rho u^2 + p per unit area and the balance then added p_in A_in - p_out A_out again. That made
the reported momentum imbalance ~1.0 (an artefact, not physics): with M_in = M_out the
residual reduced to -p_out A. The convective and pressure parts are now kept apart and the
pressure is counted exactly once, which a uniform-flow regression in test_mixing.py pins.

The inlet mass and momentum fluxes are the receipt's *nominal* ideal-gas values at the
requested temperatures. When a requested temperature lies outside the JANAF range of the
frozen mechanism (the 100 K oxidiser of job 125296683 against Tlow = 200 K) the enthalpy is
extrapolated by the table and the summary says so, brackets the energy flux at the range
limits, and no longer calls the inlet flux exact.

`hs` is the sensible enthalpy from the committed JANAF table, `hf` the formation enthalpy
(R/W * a6 of the NASA-7 low band), `K` the kinetic energy. The energy residual is therefore a
*discrete consistency* measure of the solver's enthalpy formulation, not a proof: the flux
terms use the same table as the volume integral, and conduction through the inlet/outlet is
not modelled, only bounded by the reported temperature range.

Usage:
    python3 -B mixing_metrics.py --case DIR --receipt RECEIPT.json --out metrics.json
"""
import argparse
import json
import re
from pathlib import Path

from metrics import (R_UNIVERSAL, TREF, species_table, sensible_enthalpy_MJ,
                     janaf_h_over_R, read_scalar)


def read_vector_x(path, count):
    text = path.read_text()
    m = re.search(r'internalField\s+uniform\s+\(([^;]*)\);', text)
    if m:
        return [float(m[1].split()[0])] * count
    m = re.search(r'internalField\s+nonuniform\s+List<vector>\s+(\d+)\s*\((.*?)\)\s*;', text, re.S)
    if not m:
        raise ValueError('invalid vector field ' + str(path))
    values = [float(p.split()[0]) for p in re.findall(r'\(([^()]*)\)', m[2])]
    if len(values) != count:
        raise ValueError('vector size mismatch ' + str(path))
    return values


def formation_enthalpy_J(entry):
    """Formation enthalpy: the JANAF enthalpy of formation at Tref, from the same band.

    `sensible_enthalpy_MJ` returns h(T) - h(Tref) of one NASA-7 band, so adding
    h(Tref) of the *same* band returns h(T) exactly and the pair (hs, hf) is a
    strict decomposition of the tabulated enthalpy. Taking a6 alone would mix two
    bands: for GRI CH4 a6 is -10246.6 (low) and -9468.34 (high), and a6 alone is
    h(T->0), not h(298.15), so the sum would not reproduce the table.
    """
    band = 'low' if TREF <= entry['tcommon'] else 'high'
    return R_UNIVERSAL / entry['weight'] * janaf_h_over_R(entry['coeffs'][band], TREF)


def cell_enthalpy(names, table, temperature, ys, cell):
    """Sensible and formation enthalpy of one cell's mixture, from its own T and Y."""
    hs_mix = sum(ys[n][cell] * sensible_enthalpy_MJ(table[n], temperature[cell]) for n in names)
    hf_mix = sum(ys[n][cell] * formation_enthalpy_J(table[n]) for n in names)
    return hs_mix, hf_mix


def conserved_integrals(case, time_name, names, table, geom):
    """Volume integrals of mass, x-momentum, sensible/formation/kinetic/total energy."""
    d = case / time_name
    n = geom['cells']
    T = read_scalar(d / 'T', n)
    p = read_scalar(d / 'p', n)
    rho = read_scalar(d / 'rho', n)
    ux = read_vector_x(d / 'U', n)
    ys = {name: read_scalar(d / name, n) for name in names}
    vol = geom['dx'] * geom['dy'] * geom['depth']

    mass = 0.0
    momentum = 0.0
    sensible = 0.0
    formation = 0.0
    kinetic = 0.0
    pressure_volume = 0.0
    for c in range(n):
        hs, hf = cell_enthalpy(names, table, T, ys, c)
        mass += rho[c] * vol
        momentum += rho[c] * ux[c] * vol
        sensible += rho[c] * hs * vol
        formation += rho[c] * hf * vol
        kinetic += 0.5 * rho[c] * ux[c] * ux[c] * vol
        pressure_volume += p[c] * vol
    return dict(
        cells=n, mass=mass, momentum=momentum,
        sensible_energy=sensible, formation_energy=formation,
        kinetic_energy=kinetic, pressure_volume=pressure_volume,
        total_energy=sensible + formation + kinetic - pressure_volume, T=T, p=p, rho=rho,
        ux=ux, Y=ys)


def momentum_net(outlet_momentum, inlet_momentum, pressure_in, pressure_out):
    """Net x-momentum into the control volume, with the pressure counted exactly once.

    `outlet_momentum` and `inlet_momentum` are convective fluxes rho u^2 A; `pressure_in`
    and `pressure_out` are p A on the inlet and outlet patches. A uniform flow has equal
    convective fluxes and equal p A, so this returns exactly 0.0; the earlier expression
    returned -p_out A because the outlet momentum flux already contained p.
    """
    return (inlet_momentum - outlet_momentum) + (pressure_in - pressure_out)


def patch_fluxes(state, names, table, geom):
    """Inlet (nominal, from the receipt profile) and outlet (from the saved fields) fluxes."""
    nx, ny = geom['nx'], geom['ny']
    area = geom['dy'] * geom['depth']
    fuel_cells = sum(1 for iy in range(ny) if iy < ny // 2)
    ox_cells = ny - fuel_cells
    inlet = geom['inlet']
    m_in = inlet['mass_flux']
    q_in = inlet['momentum_flux']
    e_in = inlet['energy_flux']
    p_in = geom['pressure'] * fuel_cells * area + geom['pressure'] * ox_cells * area

    m_out = 0.0
    q_out = 0.0
    e_out = 0.0
    p_out = 0.0
    T, p, rho, ux, ys = state['T'], state['p'], state['rho'], state['ux'], state['Y']
    for iy in range(ny):
        c = (nx - 1) + nx * iy          # cell adjacent to the outlet patch
        hs, hf = cell_enthalpy(names, table, T, ys, c)
        k = 0.5 * ux[c] * ux[c]
        m_out += rho[c] * ux[c] * area
        q_out += rho[c] * ux[c] * ux[c] * area          # convective momentum only
        e_out += rho[c] * ux[c] * (hs + hf + k) * area
        p_out += p[c] * area
    return dict(mass_in=m_in, mass_out=m_out, momentum_in=q_in, momentum_out=q_out,
                energy_in=e_in, energy_out=e_out, pressure_in=p_in, pressure_out=p_out)


def mixing_width(state, geom, species):
    """Crossings of the oxidiser mass fraction at the last x column, in height.

    The column is ordered by physical height (cell-centre height dy*(iy+0.5)); earlier this
    function sorted the cells from the top down and then paired them with *ascending*
    heights, so every reported height belonged to a different cell than the value at that
    height, and an asymmetric profile could be reported mirrored. The crossed height is
    interpolated in height order, the width is reported signed (y90 - y10) as well as
    absolute, and the direction says whether the oxidiser mass fraction increases or
    decreases with height, so a mirrored profile is visible instead of hiding inside an
    absolute value. `y_at_*` are heights above the bottom wall in metres. The 10/90
    crossings are searched from the top (oxidiser) down; the first crossing of each level
    is reported, and `crossings` counts how many were found so a plateau is visible.
    """
    nx, ny = geom['nx'], geom['ny']
    y = state['Y'][species]
    column = [(geom['dy'] * (iy + 0.5), y[(nx - 1) + nx * iy]) for iy in range(ny)]
    column.sort(key=lambda pair: pair[0])            # ascending height, values follow
    heights = [h for h, _ in column]
    values = [v for _, v in column]

    def crossing(target, top_down=True):
        order = range(len(values) - 1, 0, -1) if top_down else range(len(values) - 1)
        found = []
        for i in order:
            j = i - 1 if top_down else i + 1
            a, b = values[i], values[j]
            if (a - target) * (b - target) <= 0 and a != b:
                frac = (a - target) / (a - b)
                found.append(heights[i] + frac * (heights[j] - heights[i]))
        return found

    found90 = crossing(0.9)
    found50 = crossing(0.5)
    found10 = crossing(0.1)
    w90, w50, w10 = (found90[0] if found90 else None,
                     found50[0] if found50 else None,
                     found10[0] if found10 else None)
    width = None if (w90 is None or w10 is None) else abs(w90 - w10)
    signed = None if (w90 is None or w10 is None) else w90 - w10
    direction = None
    if len(values) > 1:
        direction = 'increasing' if values[-1] > values[0] else 'decreasing'
    return dict(y_at_Y90=w90, y_at_Y50=w50, y_at_Y10=w10, width_10_90=width,
                width_10_90_signed=signed, oxidiser_profile=direction,
                crossings=dict(Y90=len(found90), Y50=len(found50), Y10=len(found10)),
                column_ordered_by_height=True)


def analyse(case, receipt, time_name):
    geom = receipt['_geometry']
    names, table = geom['names'], geom['table']
    state = conserved_integrals(case, time_name, names, table, geom)
    fluxes = patch_fluxes(state, names, table, geom)
    ox_species = receipt['streams']['oxidiser']['species']
    width = mixing_width(state, geom, ox_species)

    ysum_error = 0.0
    y_min = 0.0
    negative = 0
    for c in range(geom['cells']):
        total = sum(state['Y'][name][c] for name in names)
        ysum_error = max(ysum_error, abs(total - 1.0))
        for name in names:
            value = state['Y'][name][c]
            y_min = min(y_min, value)
            if value < 0.0:
                negative += 1
    # acoustic Mach number from the local state with cp/cv = 1.4 (ideal-gas estimate only)
    mach = max(abs(state['ux'][c]) / max((1.4 * state['p'][c] / state['rho'][c]) ** 0.5, 1e-9)
               for c in range(geom['cells']))

    return dict(
        time=float(time_name),
        mass=state['mass'], momentum=state['momentum'],
        sensible_energy=state['sensible_energy'],
        formation_energy=state['formation_energy'],
        kinetic_energy=state['kinetic_energy'],
        pressure_volume=state['pressure_volume'],
        total_energy=state['total_energy'],
        fluxes=fluxes,
        mixing=width,
        bounds=dict(
            T_min=min(state['T']), T_max=max(state['T']),
            p_min=min(state['p']), p_max=max(state['p']),
            rho_min=min(state['rho']), rho_max=max(state['rho']),
            u_min=min(state['ux']), u_max=max(state['ux']),
            Y_min=y_min, species_sum_error=ysum_error,
            negative_species_cells=negative, max_mach=mach,
            pressure_excursion=max(abs(v - geom['pressure']) for v in state['p'])
            / geom['pressure']),
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--case', type=Path, required=True)
    parser.add_argument('--receipt', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()

    case = args.case.resolve(strict=True)
    receipt = json.loads(args.receipt.read_text())
    mesh = receipt['mesh']
    names, table = species_table((case / 'constant/thermo.inputData_GRI').read_text())
    streams = receipt['streams']
    rho_f = streams['ideal_gas_density_kg_m3']['fuel']
    rho_o = streams['ideal_gas_density_kg_m3']['oxidiser']
    u_f = streams['fuel']['velocity_m_per_s']
    u_o = streams['oxidiser']['velocity_m_per_s']
    T_f = streams['fuel']['temperature_K']
    T_o = streams['oxidiser']['temperature_K']
    p0 = receipt['pressure_Pa']
    area = mesh['dy'] * mesh['depth']
    fuel_cells = mesh['ny'] // 2
    ox_cells = mesh['ny'] - fuel_cells

    # Nominal inlet fluxes from the imposed profile (no field read, no interpolation). The
    # energy flux is evaluated with the frozen JANAF table at the requested temperature; when
    # that temperature is outside the table's declared range the value is an extrapolation,
    # so the summary records the range, brackets the energy flux at the range limits and
    # stops calling the inlet flux exact.
    def stream_energy(rho, u, T, species, n_cells):
        k = 0.5 * u * u
        return rho * u * (sensible_enthalpy_MJ(table[species], T)
                          + formation_enthalpy_J(table[species]) + k) * n_cells * area

    def stream_range(species):
        entry = table[species]
        return entry.get('tlow', 200.0), entry.get('thigh', 3500.0)

    def clipped(T, species):
        tlow, thigh = stream_range(species)
        return min(max(T, tlow), thigh)

    fuel_species = streams['fuel']['species']
    ox_species = streams['oxidiser']['species']
    inlet_mass = (rho_f * u_f * fuel_cells + rho_o * u_o * ox_cells) * area
    inlet_momentum = (rho_f * u_f * u_f * fuel_cells + rho_o * u_o * u_o * ox_cells) * area
    inlet_energy = (stream_energy(rho_f, u_f, T_f, fuel_species, fuel_cells)
                    + stream_energy(rho_o, u_o, T_o, ox_species, ox_cells))
    inlet_energy_clipped = (
        stream_energy(rho_f, u_f, clipped(T_f, fuel_species), fuel_species, fuel_cells)
        + stream_energy(rho_o, u_o, clipped(T_o, ox_species), ox_species, ox_cells))
    stream_range_info = {
        'fuel': dict(requested_T_K=T_f, thermo_T_K=stream_range(fuel_species),
                     evaluated_at_K=clipped(T_f, fuel_species)),
        'oxidiser': dict(requested_T_K=T_o, thermo_T_K=stream_range(ox_species),
                         evaluated_at_K=clipped(T_o, ox_species)),
    }
    out_of_range = [name for name, info in stream_range_info.items()
                    if info['requested_T_K'] != info['evaluated_at_K']]

    geom = dict(nx=mesh['nx'], ny=mesh['ny'], cells=mesh['cells'], dx=mesh['dx'],
                dy=mesh['dy'], depth=mesh['depth'], names=names, table=table,
                pressure=p0, inlet=dict(mass_flux=inlet_mass,
                                        momentum_flux=inlet_momentum,
                                        energy_flux=inlet_energy))
    receipt['_geometry'] = geom

    # Only written states carry rho: the generated 0/ directory holds the initial
    # condition (U, T, p, Y) and no thermo-derived field. Reading 0/ made the metric step
    # abort on a solve that had succeeded (job 125296683, "No such file or directory: ...
    # /0/rho"), so the time list is the states that can actually be measured, and the
    # skipped directories are recorded rather than silently dropped.
    candidates = sorted([d.name for d in case.iterdir()
                         if d.is_dir() and re.fullmatch(r'[0-9.eE+-]+', d.name)], key=float)
    found = [t for t in candidates if (case / t / 'rho').is_file()]
    skipped = [t for t in candidates if t not in found]
    results = [analyse(case, receipt, t) for t in found]

    balances = []
    for a, b in zip(results, results[1:]):
        dt = b['time'] - a['time']
        if dt <= 0:
            continue
        balance = dict(
            interval=[a['time'], b['time']], dt=dt,
            mass_accumulation=(b['mass'] - a['mass']) / dt,
            mass_net_in=b['fluxes']['mass_in'] - b['fluxes']['mass_out'],
            momentum_accumulation=(b['momentum'] - a['momentum']) / dt,
            momentum_net_in=momentum_net(b['fluxes']['momentum_out'],
                                         b['fluxes']['momentum_in'],
                                         b['fluxes']['pressure_in'],
                                         b['fluxes']['pressure_out']),
            momentum_convective_out=b['fluxes']['momentum_out'],
            momentum_convective_in=b['fluxes']['momentum_in'],
            pressure_force_in=b['fluxes']['pressure_in'],
            pressure_force_out=b['fluxes']['pressure_out'],
            energy_accumulation=(b['total_energy'] - a['total_energy']) / dt,
            energy_net_in=b['fluxes']['energy_in'] - b['fluxes']['energy_out'],
        )
        # Normalise each residual by the size of the fluxes it is made of, not by the net,
        # because the net can cancel to float noise and then any residual divides by nothing:
        # the uniform-flow self-test returned a momentum fraction of -1.0 for a residual of
        # 1.4e-20 against a net of 1.4e-20 (the earlier 170.9-style mass and momentum figures
        # reported from this run had the same defect). The fraction of the net is kept beside
        # it, and reported as null when the net is too small to divide by.
        scale_m = max(abs(b['fluxes']['mass_in']), abs(b['fluxes']['mass_out']), 1e-30)
        scale_e = max(abs(b['fluxes']['energy_in']), abs(b['fluxes']['energy_out']), 1e-30)
        scale_q = max(abs(b['fluxes']['momentum_in']), abs(b['fluxes']['momentum_out']), 1e-30)
        balance['mass_imbalance_fraction'] = (
            balance['mass_accumulation'] - balance['mass_net_in']) / scale_m
        balance['momentum_imbalance_fraction'] = (
            balance['momentum_accumulation'] - balance['momentum_net_in']) / scale_q
        balance['energy_imbalance_fraction'] = (
            balance['energy_accumulation'] - balance['energy_net_in']) / scale_e
        for name, scale in (('mass', scale_m), ('momentum', scale_q), ('energy', scale_e)):
            net = balance[name + '_net_in']
            balance[name + '_net_in_over_flux'] = net / scale
            balance[name + '_net_significant'] = abs(net) > 1e-9 * scale
            balance[name + '_imbalance_over_net'] = (
                (balance[name + '_accumulation'] - net) / abs(net)
                if balance[name + '_net_significant'] else None)
        balance['normalisation'] = (
            'imbalance_fraction = (accumulation - net_in) / max(|inlet flux|, |outlet flux|); '
            '_imbalance_over_net divides by |net_in| only when |net_in| > 1e-9 * flux scale')
        balances.append(balance)

    summary = dict(
        schema='of8-mixing-metrics-v1',
        case=str(case),
        receipt=str(args.receipt),
        source_commit=receipt.get('source_commit'),
        cells=geom['cells'], times=found, skipped_states=skipped,
        inlet_flux=dict(total_mass_flux_kg_per_s=inlet_mass,
                        total_momentum_flux_kg_m_per_s2=inlet_momentum,
                        total_energy_flux_J_per_s=inlet_energy,
                        energy_flux_at_thermo_limits_J_per_s=inlet_energy_clipped,
                        streams=stream_range_info,
                        out_of_range_temperature=out_of_range,
                        basis=('nominal frozen-profile values: mass and convective momentum '
                               'from the receipt densities/velocities, energy from the JANAF '
                               'table at the requested temperature')),
        generation=dict(id='posthoc-corrected-r13',
                        schema='of8-mixing-metrics-v2',
                        changes=['outlet momentum flux is convective rho u^2 A only; the '
                                 'pressure force is added once',
                                 'mixing crossings are paired with their own cell heights '
                                 'and reported signed',
                                 'inlet energy flux flags out-of-range temperatures and is '
                                 'bracketed at the table limits'],
                        note=('supersedes the momentum and mixing numbers of the earlier '
                              'of8-mixing-metrics-v1 file for the same saved fields; the '
                              'solver output is unchanged and no case was rerun')),
        per_time=results, balances=balances,
        scope=('bounded 2-D cold-mixing diagnostic: mass/momentum/energy flux balance, '
               'positivity and species closure only; not a G2 replication'),
    )
    args.out.write_text(json.dumps(summary, indent=2, sort_keys=True, default=str) + '\n')
    print(json.dumps(dict(case=str(case), times=found, inlet_mass=inlet_mass,
                          n_balances=len(balances)), indent=2))


if __name__ == '__main__':
    main()
