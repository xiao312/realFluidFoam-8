"""Postprocess the OF8 contact-advection cases against the periodic exact solution.

The cases are generated by `prepare_advection_case.py`: periodic in x, ideal gas at
1 atm, u = 10 m/s, an error-function temperature contact 300 K -> 3000 K, chemistry
off. Because the domain is periodic there is no boundary flux, so the conserved
totals are statements about the discretisation alone:

    mass     = sum(rho) * V
    momentum = sum(rho * Ux) * V
    energy   = sum(rho * (hs + hf - p/rho + 0.5 * |U|^2)) * V

and the exact solution is a rigid shift of the initial temperature profile, so the
pointwise error T(x, t) - T0(x - u t) measures numerical diffusion without any
reference data. The two quantities the registered target actually plots are reported
as amplitudes relative to their uniform initial values: the spurious pressure
deviation max|p - p0| / p0 and the velocity deviation max|U - u0|.

Usage:
    python3 -B advection_metrics.py --case DIR --times 0.005,0.01,0.015,0.02 \
        [--out FILE]
"""
import argparse
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from metrics import (R_UNIVERSAL, block_geometry, janaf_cp_over_R, len_table_probe,
                     read_scalar, read_vector_z, sensible_enthalpy_MJ, species_table)
from expected_energy import formation_enthalpy

VELOCITY = 10.0
PRESSURE = 101325.0


def time_dirs(case):
    names = []
    for path in case.iterdir():
        if path.is_dir():
            try:
                float(path.name)
            except ValueError:
                continue
            names.append(path.name)
    return sorted(names, key=float)


def parse_time(value):
    try:
        return float(value)
    except ValueError:
        return float(value.replace('D', 'e').replace('d', 'e'))


def read_profile(case, time_name, names, table):
    directory = case / time_name
    n = len_table_probe(directory)
    T = read_scalar(directory / 'T', n)
    p = read_scalar(directory / 'p', n)
    ys = {}
    for name in names:
        path = directory / name
        ys[name] = read_scalar(path, n) if path.exists() else [0.0] * n
    return dict(n=n, T=T, p=p, Y=ys, dir=directory)


def mixture_molar_mass(ys, table, count):
    """Per-cell mixture molar mass [kg/kmol] from mass fractions."""
    inverse = [0.0] * count
    for name, values in ys.items():
        weight = table[name]['weight']
        for i in range(count):
            inverse[i] += values[i] / weight
    return [1.0 / v for v in inverse]


def exact_temperature(case, time, dx, n):
    initial = read_scalar(case / '0' / 'T', n)
    centres = [(i + 0.5) * dx for i in range(n)]
    length = n * dx
    shifted = []
    for x in centres:
        source = (x - VELOCITY * time) % length
        position = source / dx - 0.5
        i0 = int(math.floor(position))
        fraction = position - i0
        i0 %= n
        i1 = (i0 + 1) % n
        shifted.append((1.0 - fraction) * initial[i0] + fraction * initial[i1])
    return initial, shifted


def analyse(case, times):
    case = Path(case)
    geometry = block_geometry(case)
    dx = geometry['dx']
    names, table = species_table((case / 'constant' / 'thermo.inputData_GRI').read_text())
    hf_per_kg = {name: formation_enthalpy(table[name]) for name in names}

    initial = read_profile(case, '0', names, table)
    # the initial directory has no rho field: build it from the ideal-gas law
    m0 = mixture_molar_mass(initial['Y'], table, initial['n'])
    rho0 = [initial['p'][i] * m0[i] / (R_UNIVERSAL * initial['T'][i])
            for i in range(initial['n'])]
    he0 = [sum(initial['Y'][name][i] * sensible_enthalpy_MJ(table[name], initial['T'][i])
               for name in names) for i in range(initial['n'])]
    ux0 = read_vector_z(case / '0' / 'U', initial['n'])

    # the case is one cell thick in y and z with empty side patches; the slab is
    # quoted per unit area, exactly like the energy diagnostic
    volume = dx
    def totals(rho, he, hf, p, ux, n):
        mass = sum(rho) * volume
        momentum = sum(rho[i] * ux[i] for i in range(n)) * volume
        energy = sum(rho[i] * (he[i] + hf[i] - p[i] / rho[i] + 0.5 * ux[i] ** 2)
                     for i in range(n)) * volume
        return mass, momentum, energy

    hf0 = [sum(initial['Y'][name][i] * hf_per_kg[name] for name in names)
           for i in range(initial['n'])]

    mass_0, momentum_0, energy_0 = totals(rho0, he0, hf0, initial['p'], ux0, initial['n'])

    rows = []
    for name in times:
        state = read_profile(case, name, names, table)
        n = state['n']
        ux = read_vector_z(state['dir'] / 'U', n)
        rho = read_scalar(state['dir'] / 'rho', n)
        he = [sum(state['Y'][s][i] * sensible_enthalpy_MJ(table[s], state['T'][i])
                  for s in names) for i in range(n)]
        hf = [sum(state['Y'][s][i] * hf_per_kg[s] for s in names)
              for i in range(n)]
        mass, momentum, energy = totals(rho, he, hf, state['p'], ux, n)
        p_dev = max(abs(state['p'][i] - PRESSURE) for i in range(n)) / PRESSURE
        u_dev = max(abs(ux[i] - VELOCITY) for i in range(n))
        _, shifted = exact_temperature(case, parse_time(name), dx, n)
        scale = max(shifted) - min(shifted)
        l2 = math.sqrt(sum((state['T'][i] - shifted[i]) ** 2 for i in range(n)) / n)
        species_sum_error = max(abs(sum(state['Y'][s][i] for s in names) - 1.0)
                                for i in range(n))
        cp_error = None
        cp_path = state['dir'] / 'Cp'
        if cp_path.exists():
            cp = read_scalar(cp_path, n)
            cp_error = 0.0
            for i in range(n):
                janaf = sum(state['Y'][s][i] * R_UNIVERSAL / table[s]['weight']
                            * janaf_cp_over_R(
                                table[s]['coeffs']['low' if state['T'][i] <= table[s]['tcommon']
                                                  else 'high'], state['T'][i])
                            for s in names)
                if abs(janaf) > 0.0:
                    cp_error = max(cp_error, abs(cp[i] / janaf - 1.0))
        rows.append(dict(
            time=name,
            cells=n,
            mass_kg_per_m2=mass, momentum=momentum, total_energy_J_per_m2=energy,
            mass_rel_drift=(mass - mass_0) / mass_0,
            momentum_rel_drift=(momentum - momentum_0) / max(abs(momentum_0), 1e-30),
            energy_rel_drift=(energy - energy_0) / max(abs(energy_0), 1e-30),
            pressure_deviation_rel=p_dev,
            velocity_deviation_m_per_s=u_dev,
            temperature_min_K=min(state['T']), temperature_max_K=max(state['T']),
            density_min_kg_per_m3=min(rho), density_max_kg_per_m3=max(rho),
            species_sum_max_error=species_sum_error,
            cp_max_rel_error_vs_janaf=cp_error,
            temperature_l2_error_K=l2,
            temperature_l2_relative_to_jump=l2 / scale if scale else None,
            temperature_max_abs_error_K=max(abs(state['T'][i] - shifted[i])
                                            for i in range(n)),
        ))

    return dict(
        case=str(case),
        target='schmitt2020-fig-5',
        geometry=geometry,
        times=rows,
        initial=dict(mass_kg_per_m2=mass_0, momentum=momentum_0,
                     total_energy_J_per_m2=energy_0),
        scope=('numerics-only stand-in for the registered 6 MPa oxygen case; the '
               'periodic domain has no boundary flux, so conservation is exact in '
               'exact arithmetic and any drift is discretisation error'),
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--case', type=Path, required=True)
    parser.add_argument('--times', required=True)
    parser.add_argument('--out', type=Path, default=None)
    args = parser.parse_args()

    case = args.case
    times = [t for t in args.times.split(',') if t]
    if times == ['all']:
        times = [name for name in time_dirs(case) if float(name) != 0.0]
    result = analyse(case, times)
    text = json.dumps(result, indent=2)
    if args.out:
        args.out.write_text(text + '\n')
        print('wrote %s' % args.out)
    else:
        print(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
